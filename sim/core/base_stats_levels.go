// The base stats of a race and class at a level: BaseStats at level 60, the rows above below it.
func BaseStatsAt(race proto.Race, class proto.Class, level int32) stats.Stats {
	key := BaseStatsKey{Race: race, Class: class}
	rows, ok := classLevelStats[class]
	if level >= CharacterLevel || !ok || level < 1 {
		return BaseStats[key]
	}
	row := rows[level-1]
	base := ClassBaseStats[class]
	base[stats.Strength] = row[0]
	base[stats.Agility] = row[1]
	base[stats.Stamina] = row[2]
	base[stats.Intellect] = row[3]
	base[stats.Spirit] = row[4]
	base[stats.Health] = row[5]
	// Flat attack power grows by 3 a level for warriors and paladins and by 2 for hunters, rogues and
	// shamans; ClassBaseStats holds the level-60 value. Ranged attack power is level×2 − 10.
	base[stats.AttackPower] -= float64(attackPowerPerLevel[class] * (CharacterLevel - level))
	if base[stats.RangedAttackPower] != 0 {
		base[stats.RangedAttackPower] -= float64(2 * (CharacterLevel - level))
	}
	extra := ExtraClassBaseStats[class]
	if extra[stats.Mana] != 0 {
		extra[stats.Mana] = row[6]
	}
	return base.Add(RaceOffsets[race]).Add(extra)
}

var attackPowerPerLevel = map[proto.Class]int32{
	proto.Class_ClassWarrior: 3,
	proto.Class_ClassPaladin: 3,
	proto.Class_ClassHunter:  2,
	proto.Class_ClassRogue:   2,
	proto.Class_ClassShaman:  2,
}

